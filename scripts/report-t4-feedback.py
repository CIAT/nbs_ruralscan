#!/usr/bin/env python3
"""Render tracked reviewer requests without treating quarantine as repair."""

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    audit = ROOT / "pipeline/t4_audit/agroforestry"
    items = json.loads((audit / "review_followups.json").read_text()).values()
    with (ROOT / "schema/registers/EV_evidence_register.csv").open() as stream:
        evidence = {r["evidence_id"]: r for r in csv.DictReader(stream)}
    counts = Counter(x["status"] for x in items)
    lines = [
        "# T4 reviewer feedback follow-ups",
        "",
        "Generated by `scripts/report-t4-feedback.py` from the feedback tracker.",
        "",
        f"{counts['needs_review']} requests need verification; {counts['quarantined']} concern excluded records; {counts['resolved']} have checked corrective fields.",
        "",
        "These are historical requests, not a new review assignment. Some may already be addressed; verify the current source display and extraction before closing. No evidence approval or T4 rule changes result from this inventory.",
        "",
        "Closure records must name existing evidence and fingerprint the corrected fields. These checks detect stale corrections; they do not replace source review.",
        "",
    ]
    for status, title in [
        ("needs_review", "Needs verification"),
        ("resolved", "Verified corrections"),
        ("quarantined", "Excluded records — not claimed repaired"),
    ]:
        lines += ["## " + title, ""]
        for item in sorted(
            (x for x in items if x["status"] == status),
            key=lambda x: (x.get("reason", ""), x["evidence_id"]),
        ):
            unit = evidence[item["evidence_id"]]
            lines += [
                f"### {unit['source_id']} · {unit['variable']}",
                "",
                f"Record: `{item['evidence_id']}`. Reviewer: {item['reviewer']}. Reason: {item.get('reason') or 'Free-text request'}.",
                "",
                "Feedback: "
                + (item["note"] or "No free-text note; coded reason above."),
                "",
                "Disposition: " + item["resolution"],
                "",
            ]
    (audit / "review_followups.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
