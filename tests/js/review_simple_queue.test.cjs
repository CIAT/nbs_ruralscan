const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('docs/dashboard.html','utf8');
const window={};let answered=new Set(),issues={};
const ctx=vm.createContext({window,document:{getElementById:()=>null},renderVfWorklist:()=>{},vfHasAnswerForReview:id=>answered.has(id),vfClarificationsFor:id=>issues[id]||[]});
vm.runInContext(html.slice(html.indexOf('function vfSimpleQueue('),html.indexOf('function _vfInScope(')),ctx);
const row=(id,extra={})=>({ev:{evidence_id:id,_reviewQueue:'first'},me:false,meApplied:false,dropped:false,...extra});
assert(ctx.vfSimpleMatch(row('new'),'todo'));
assert(!ctx.vfSimpleMatch(row('saved',{me:true,myDec:'ok'}),'todo'));
assert(ctx.vfSimpleMatch(row('saved',{me:true,myDec:'ok'}),'mine'));
assert(ctx.vfSimpleMatch(row('query',{me:true,myDec:'flag'}),'waiting'));
assert(!ctx.vfSimpleMatch(row('drop',{me:true,dropped:true,myDec:'drop'}),'todo'));
assert(ctx.vfSimpleMatch(row('drop',{me:true,dropped:true,myDec:'drop'}),'mine'));
answered.add('returned');assert(ctx.vfSimpleMatch(row('returned',{me:true,meApplied:true,myDec:'query'}),'todo'));
assert(!ctx.vfSimpleMatch(row('returned',{me:true,meApplied:true,myDec:'query'}),'waiting'));
assert(!ctx.vfSimpleMatch(row('status',{ev:{evidence_id:'status',_reviewQueue:'approval_only'}}),'todo'));
assert(ctx.vfSimpleMatch(row('conflict',{ev:{evidence_id:'conflict',_reviewQueue:'unresolved',_reviewConflict:true}}),'todo'));
ctx.vfSimpleQueue('mine');assert.equal(window._vfAxStatus,'any');assert.equal(window._vfAxMe,'any');
assert(!html.includes('Review queues — separate, non-overlapping counts'));
assert(html.includes('More filters'));assert(html.includes('Submission details'));
console.log('Simple queues: new, answered, pending, queried, dropped, maintenance and conflict cases passed');
const repeated=row('repeat',{ev:{evidence_id:'repeat',_reviewQueue:'unresolved',_reviewConflict:true},me:true,meApplied:true,myDec:'drop',conflictReviewed:true});
assert(!ctx.vfSimpleMatch(repeated,'todo'));
assert(ctx.vfSimpleMatch(repeated,'mine'));
assert(ctx.vfSimpleMatch(repeated,'advanced'));
assert(ctx.vfSimpleMatch({...repeated,conflictReviewed:false},'todo'));
answered.add('repeat');assert(ctx.vfSimpleMatch(repeated,'todo'));
