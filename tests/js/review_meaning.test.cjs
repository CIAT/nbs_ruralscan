const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('docs/dashboard.html', 'utf8');
const source = html.slice(html.indexOf('  function vfReviewMeaning'), html.indexOf('  function _vfTabular'));
const ctx = {vfEsc: s => String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')};
vm.createContext(ctx); vm.runInContext(source, ctx);
const ev = JSON.parse(fs.readFileSync('schema/registers/EV_evidence_register.json','utf8'));
const rows = Array.isArray(ev) ? ev : ev.rows;
const ndvi = rows.find(r => r.evidence_id === 'ev_T4_model_use_ahmad2020_ndvi');
assert(ndvi);
const result = ctx.vfReviewMeaning(ndvi);
assert(result.includes('16.66%'));
assert(result.includes('PDF p10'));
assert(result.includes('review/img/ahmad2020_table2_recovery.png'));
assert(result.includes('does not set a T4 cutoff'));
assert(result.includes('Keep approves this extraction'));
const species = ctx.vfReviewMeaning({context:{model_use:{scope:'species_selection'}},use_role:'dataset'});
assert(species.includes('Counted separately'));
assert(!species.includes('undefined'));
const programme = ctx.vfReviewMeaning({relationship:{criterion_kind:'programme_eligibility'},context:{review_needed:'<unsafe>'}});
assert(programme.includes('named programme only'));
assert(programme.includes('&lt;unsafe>'));
const empty = ctx.vfReviewMeaning({});
assert(empty.includes('No numeric threshold or class rule extracted'));
console.log('Review meaning: 4 scenarios passed');
