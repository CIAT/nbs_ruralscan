const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('docs/dashboard.html','utf8');
for(const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(m[1]);
const ctx=vm.createContext({window:{},renderVfWorklist:()=>{}});
vm.runInContext(html.slice(html.indexOf('function _vfReviewBucket'),html.indexOf('function _vfInScope')),ctx);
const classify=ctx._vfReviewBucket;
assert.equal(classify({},{}),'first');
assert.equal(classify({reviewer_ok:true},{Pete:'keep'}),'recorded');
assert.equal(classify({reviewer_ok:true},{}),'approval_only');
assert.equal(classify({reviewer_ok:'true'},{Pete:'ok'}),'recorded');
assert.equal(classify({reviewer_ok:'false'},{Pete:'ok'}),'unresolved');
assert.equal(classify({reviewer_ok:true},{Pete:'query'}),'unresolved');
assert.equal(classify({reviewer_ok:true},{Pete:'ok',Namita:'drop'}),'unresolved');
assert.equal(classify({review_state:'dropped',reviewer_ok:true},{Pete:'ok'}),'dropped');
ctx.window._vfAxMe='no';ctx.window._vfTablesOnly=true;
ctx.vfReviewQueue('unresolved');
assert.equal(ctx.window._vfAxMe,'any');assert.equal(ctx.window._vfTablesOnly,false);
assert.equal(ctx.window._vfReconcile,'unresolved');
console.log('Reconciliation buckets, filter reset and all inline JS syntax passed.');
