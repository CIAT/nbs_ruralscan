const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('docs/dashboard.html', 'utf8');
const source = html.slice(html.indexOf('var _vfR2T='), html.indexOf('// Gap rows carry'));
const window = {_vfScope:{nbs:'agroforestry',table:'T4'}};
const ctx = vm.createContext({window});
vm.runInContext(source, ctx);
const row = {nbs_id:'agroforestry',use_role:'operational_risk'};
assert.equal(ctx._vfInScope(row), true);
assert.equal(ctx._vfInScope({...row,use_role:'structural_suitability'}), true);
assert.equal(ctx._vfInScope({...row,use_role:'nbs_effect'}), false);
assert.equal(ctx._vfInScope({...row,nbs_id:'wetland_management'}), false);
window._vfScope.family='agroforestry__regeneration';
assert.equal(ctx._vfInScope(row), false);
assert.equal(ctx._vfInScope({...row,suitability_family_id:window._vfScope.family}), true);
window._vfScope={nbs:'agroforestry',table:'T3/T6'};
assert.equal(ctx._vfInScope(row), false);
assert(html.includes("operational_risk:'M2b'"));
console.log('Combined T4/M2b review scope passed; analytical labels preserved.');
